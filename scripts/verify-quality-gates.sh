assert_file_exists() {
  local path="$1"
  if [[ ! -f "$path" ]]; then
    echo "[quality-gates] missing file: $path" >&2
    exit 1
  fi
}

assert_file_contains() {
  local path="$1"
  local pattern="$2"
  if ! grep -Fq -- "$pattern" "$path"; then
    echo "[quality-gates] expected pattern '$pattern' in $path" >&2
    exit 1
  fi
}

assert_file_not_contains() {
  local path="$1"
  local pattern="$2"
  if grep -Fq -- "$pattern" "$path"; then
    echo "[quality-gates] unexpected pattern '$pattern' in $path" >&2
    exit 1
  fi
}

assert_file_not_matches() {
  local path="$1"
  local pattern="$2"
  if grep -Eq -- "$pattern" "$path"; then
    echo "[quality-gates] unexpected regex '$pattern' in $path" >&2
    exit 1
  fi
}

assert_file_matches() {
  local path="$1"
  local pattern="$2"
  if ! grep -Eq -- "$pattern" "$path"; then
    echo "[quality-gates] expected regex '$pattern' in $path" >&2
    exit 1
  fi
}

assert_k8s_images_are_release_tagged() {
  local path relative_path line image image_name

  for path in "$repo_root"/deploy/kubernetes/*.yaml; do
    relative_path="${path#$repo_root/}"
    while IFS= read -r line; do
      line="${line%%#*}"
      image="${line#*image:}"
      image="${image#"${image%%[![:space:]]*}"}"
      image="${image%%[[:space:]]*}"
      image="${image%\"}"
      image="${image#\"}"
      image="${image%\'}"
      image="${image#\'}"

      if [[ "$image" == *":latest" || "$image" == *":latest@"* ]]; then
        echo "[quality-gates] Kubernetes image must not use latest: $relative_path -> $image" >&2
        exit 1
      fi

      if [[ "$image" == *@sha256:* ]]; then
        continue
      fi

      image_name="${image##*/}"
      if [[ "$image_name" != *:* ]]; then
        echo "[quality-gates] Kubernetes image must use an explicit tag or digest: $relative_path -> $image" >&2
        exit 1
      fi
    done < <(grep -E '^[[:space:]]*image:[[:space:]]*[^[:space:]]+' "$path" || true)
  done
}

assert_file_count_at_least() {
  local path="$1"
  local pattern="$2"
  local minimum="$3"
  local count

  count=$(grep -F -c -- "$pattern" "$path" || true)
  if [[ -z "$count" ]]; then
    count=0
  fi

  if (( count < minimum )); then
    echo "[quality-gates] expected at least $minimum occurrences of '$pattern' in $path; found $count" >&2
    exit 1
  fi
}

assert_git_tracked() {
  local path="$1"
  local relative_path="${path#$repo_root/}"

  if ! git -C "$repo_root" ls-files --error-unmatch "$relative_path" >/dev/null 2>&1; then
    echo "[quality-gates] file must be tracked before release: $relative_path" >&2
    exit 1
  fi
}

